export function getTermsByLetter(letter) {
  if (!letter) return [];

  return terminology.filter((item) =>
    String(item.term || "").startsWith(letter)
  );
}

export function getTermById(id) {
  return terminology.find(
    (item) => item.id === id
  ) || null;
}

export function searchTerms(query = "") {
  const value = String(query).trim().toLowerCase();

  if (!value) {
    return terminology;
  }

  return terminology.filter((item) => {
    const searchableText = [
      item.term,
      item.pashto?.term,
      item.pashto?.definition,
      item.pashto?.explanation,
      item.pashto?.example,
      item.dari?.term,
      item.dari?.definition,
      item.dari?.explanation,
      item.dari?.example,
      item.english?.term,
      item.english?.definition,
      item.english?.explanation,
      item.english?.example
    ]
      .join(" ")
      .toLowerCase();

    return searchableText.includes(value);
  });
}